export function monsterById(id) {
  return MONSTER_CATALOG.find((monster) => monster.id === id) ?? null;
}

export function lootById(id) {
  return LOOT_CATALOG.find((item) => item.id === id) ?? null;
}

export function eventById(id) {
  return EVENT_CATALOG.find((event) => event.id === id) ?? null;
}
